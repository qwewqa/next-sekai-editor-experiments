// Writes src/preview/assets/builtinResources.ts: the SHA-1 of each required resource of the
// Built-in packages and of the bundled Default and Next SEKAI 02 ones, so Open's package list
// knows a package's copy of them without fetching anything. Run with tsx
// (`npx tsx scripts/builtin-resources.mjs`) after a package under public/ changes.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { fields } from '../src/preview/assets/files/item.ts'
import { ZipReader } from '../src/zip/index.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const packages = [
    ['builtin/skin', 'builtin', 'skin'],
    ['builtin/particle', 'builtin', 'particle'],
    ['builtin/background', 'builtin', 'background'],
    ['builtin/effect', 'builtin', 'effect'],
    ['resource/skin', 'default', 'skin'],
    ['resource/particle', 'default', 'particle'],
    ['resource/effect', 'default', 'effect'],
    ['resource/skin2', 'nextSekai02', 'skin'],
    ['resource/effect2', 'nextSekai02', 'effect'],
]

const categories = {
    skin: 'skins',
    particle: 'particles',
    background: 'backgrounds',
    effect: 'effects',
}

const rows = []
for (const [path, source, type] of packages) {
    const reader = await ZipReader.open(
        new Blob([readFileSync(resolve(root, `public/${path}.scp`))]),
    )
    const read = (name) => reader.read(reader.get(name), { maxSize: 256 * 1024 * 1024 })
    const list = JSON.parse(
        new TextDecoder().decode(await read(`sonolus/${categories[type]}/list`)),
    )
    const [item] = list.items
    const hashes = []
    for (const field of fields[type]) {
        const bytes = await read(item[field].url.replace(/^\/+/, ''))
        hashes.push(`            ${field}: '${createHash('sha1').update(bytes).digest('hex')}',`)
    }
    rows.push(
        '    {',
        `        source: '${source}',`,
        `        type: '${type}',`,
        '        hashes: {',
        ...hashes,
        '        },',
        '    },',
    )
}

writeFileSync(
    resolve(root, 'src/preview/assets/builtinResources.ts'),
    [
        '// Generated by scripts/builtin-resources.mjs from public/builtin and public/resource.',
        '',
        "import type { AssetType } from './types'",
        '',
        "export type BuiltinSource = 'builtin' | 'default' | 'nextSekai02'",
        '',
        '/** The SHA-1 of each required resource of the Built-in, Default and Next SEKAI 02 items. */',
        'export const builtinResources: readonly {',
        '    source: BuiltinSource',
        '    type: AssetType',
        '    hashes: Readonly<Record<string, string>>',
        '}[] = [',
        ...rows,
        ']',
        '',
    ].join('\n'),
)
console.log('Wrote src/preview/assets/builtinResources.ts')
