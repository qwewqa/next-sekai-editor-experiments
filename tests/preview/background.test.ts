test('background corners match the game engine reference', () => {
    for (const [imageAspectRatio, fixtures] of [
        [16 / 9, engineCases],
        [1, squareCases],
    ] as const)
        for (const fixture of fixtures) {
            const viewport = createViewport(fixture.aspect * 900, 900)
            const cameras = [fixture.camera]
            const quad = layoutBackground(
                viewport,
                cameras,
                getCameraInfo(viewport, cameras, 0),
                imageAspectRatio,
            )
            for (const [index, corner] of (['bl', 'tl', 'tr', 'br'] as const).entries()) {
                close(quad[corner].x, fixture.corners[index]![0]!)
                close(quad[corner].y, fixture.corners[index]![1]!)
            }
        }
})

test('rotation overscan accounts for the whole chart and stays fixed while seeking', () => {
    const viewport = createViewport(1600, 900)
    const cameras = [camera(), camera({ time: 10, rotate: -Math.PI })]
    const at = (time: number) =>
        layoutBackground(viewport, cameras, getCameraInfo(viewport, cameras, time))
    const first = at(-1)
    const width = (quad: ReturnType<typeof at>) =>
        Math.hypot(quad.tr.x - quad.tl.x, quad.tr.y - quad.tl.y)
    assert.ok(width(first) > width(layoutBackground(viewport, [camera()], defaultCameraInfo())))
    for (const time of [0, 2.5, 5, 7.5, 10, 20, -1]) close(width(at(time)), width(first))
    assert.deepEqual(at(-1), first)

    // A camera edit supplies a new compiled array and must invalidate overscan.
    const edited = [camera(), camera({ time: 10, rotate: 0.1 })]
    assert.ok(
        width(layoutBackground(viewport, edited, getCameraInfo(viewport, edited, 0))) <
            width(first),
    )
})

test('camera lane and size do not independently pan or stretch the background', () => {
    const viewport = createViewport(1600, 900)
    const cameras = [camera()]
    const base = getCameraInfo(viewport, cameras, 0)
    assert.deepEqual(
        layoutBackground(viewport, cameras, { ...base, lane: 5, size: 2, stageTilt: 0 }),
        layoutBackground(viewport, cameras, base),
    )
})

test("a background's aspect ratio and fit place its image before camera motion", () => {
    const half = (quad: ReturnType<typeof layoutBackground>) => ({
        width: quad.tr.x,
        height: quad.tr.y,
    })
    // A 1600 x 900 screen is 16:9; a 4:3 image on it.
    const screen = createViewport(1600, 900)
    const place = (fit: 'cover' | 'contain' | 'width' | 'height', ratio = 4 / 3) =>
        half(layoutBackground(screen, [], defaultCameraInfo(), ratio, fit))
    // Cover fills the screen: the image is as wide as it, and taller.
    close(place('cover').width, 16 / 9)
    close(place('cover').height, 16 / 9 / (4 / 3))
    // Contain fits inside: as tall as the screen, and narrower.
    close(place('contain').height, 1)
    close(place('contain').width, 4 / 3)
    // Width and height match one side exactly, whatever the other does.
    close(place('width').width, 16 / 9)
    close(place('height').height, 1)
    close(place('height').width, 4 / 3)
    // A 21:9 image on 16:9: contain is as wide as the screen.
    close(place('contain', 21 / 9).width, 16 / 9)
    close(place('contain', 21 / 9).height, 16 / 9 / (21 / 9))
    // The defaults, used before a background has loaded, are a 16:9 cover.
    const plain = half(layoutBackground(screen, [], defaultCameraInfo()))
    close(plain.width, place('cover', 16 / 9).width)
    close(plain.height, place('cover', 16 / 9).height)
})
