const camera = (overrides: Partial<CameraChange> = {}): CameraChange => ({
    time: 0,
    lane: 0,
    size: 6,
    zoom: 1,
    zoomTargetLane: 0,
    zoomTargetY: 0,
    zoomVerticalAlign: 0,
    rotate: 0,
    stageTilt: 1,
    ease: EaseType.linear,
    ...overrides,
})

const close = (actual: number, expected: number) =>
    assert.ok(Math.abs(actual - expected) < 1e-10, `${actual} != ${expected}`)

test('charts without cameras keep the original background cover fit in every aspect', () => {
    for (const [width, height, halfWidth, halfHeight] of [
        [1600, 900, 16 / 9, 1],
        [2100, 900, 21 / 9, 21 / 16],
        [1200, 900, 16 / 9, 1],
    ] as const) {
        const quad = layoutBackground(createViewport(width, height), [], defaultCameraInfo())
        close(quad.bl.x, -halfWidth)
        close(quad.bl.y, -halfHeight)
        close(quad.tl.x, -halfWidth)
        close(quad.tl.y, halfHeight)
        close(quad.tr.x, halfWidth)
        close(quad.tr.y, halfHeight)
        close(quad.br.x, halfWidth)
        close(quad.br.y, -halfHeight)
    }
})

