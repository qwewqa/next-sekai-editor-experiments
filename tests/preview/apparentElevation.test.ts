const keys = ['a00', 'a01', 'a02', 'a10', 'a11', 'a12', 'elevation'] as const

const closeScreen = (actual: StageScreenTransform, expected: Screen, label: string) => {
    keys.forEach((key, i) =>
        assert.ok(
            Math.abs(actual[key] - expected[i]!) <= 1e-12,
            `${label} ${key}: ${actual[key]} != ${expected[i]}`,
        ),
    )
}

test('revision 2 elevation matches the engine across tilts, camera rotations and the clamp', () => {
    const viewport = createViewport(1600, 900)
    for (const [
        elevation,
        [t, wScale, hScale, xTranslate, rotate, stageTilt, sizeZoom],
        projection,
        stage,
        screen,
    ] of cases) {
        const camera: LayoutTransform = {
            t,
            wScale,
            hScale,
            xTranslate,
            rotate,
            stageTilt,
            sizeZoom,
        }
        const label = `tilt ${stageTilt}, rotate ${rotate}, elevation ${elevation}`
        closeScreen(elevationProjection(camera, elevation), projection, label)
        const transform = computeStageTransform(viewport, camera, 0.3, 0.5, -0.2, 2, 0, elevation)
        // Zero is stored exactly, as identity checks read it.
        if (elevation === 0) assert.ok(transform.projection.elevation === 0, label)
        ;(['px', 'py', 'tx', 'ty'] as const).forEach((key, i) =>
            assert.ok(Math.abs(transform[key] - stage[i]!) <= 1e-12, `${label} ${key}`),
        )
        closeScreen(stageTransformToAffine(transform), screen, label)
    }
})
